const FALLBACK = 'circle';

type IconNode = [tag: string, attributes: Record<string, string>][];

function isIconNodes(value: unknown): value is Record<string, IconNode> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function markup(nodes: Record<string, IconNode>, name: string): string {
  const icon = nodes[name];
  if (!Array.isArray(icon)) throw new Error(`Lucide has no icon named "${name}".`);
  return icon
    .map(([tag, attributes]) => {
      const attrs = Object.entries(attributes)
        .map(([key, value]) => {
          if (!/^[a-z-]+$/.test(key) || /["<>&]/.test(value))
            throw new Error(`Unexpected attribute in Lucide icon "${name}".`);
          return ` ${key}="${value}"`;
        })
        .join('');
      if (!/^[a-z]+$/.test(tag)) throw new Error(`Unexpected element in Lucide icon "${name}".`);
      return `<${tag}${attrs}/>`;
    })
    .join('');
}

/** The generated Rust module. */
async function iconsModule(): Promise<string> {
  const packageJson = JSON.parse(
    await readFile(require.resolve('lucide-static/package.json'), 'utf8'),
  ) as { version?: unknown };
  const nodes: unknown = JSON.parse(
    await readFile(require.resolve('lucide-static/icon-nodes.json'), 'utf8'),
  );
  if (!isIconNodes(nodes) || typeof packageJson.version !== 'string')
    throw new Error('lucide-static is missing or has an unexpected layout.');
  const arms = ICONS.map(
    ([names, lucide]) =>
      `        ${names.map((name) => `"${name}"`).join(' | ')} => r#"${markup(nodes, lucide)}"#,`,
  );
  return [
    `//! Lucide icons (lucide-static ${packageJson.version}, ISC licence), generated by`,
    '//! `scripts/build-icons.ts`. Do not edit: change the name map there and rerun it.',
    '',
    '/// Inner SVG markup for a workspace icon: 24×24 viewBox, stroked with `currentColor`.',
    '/// Every string is a compile-time constant produced from the Lucide package.',
    '#[rustfmt::skip]',
    "pub(crate) fn icon_markup(name: &str) -> &'static str {",
    '    match name {',
    ...arms,
    `        _ => r#"${markup(nodes, FALLBACK)}"#,`,
    '    }',
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const generated = await iconsModule();
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '');
    if (current !== generated) {
      console.error('app/src/icons.rs is stale. Run: node scripts/build-icons.ts');
      process.exit(1);
    }
  } else {
    await writeFile(OUTPUT, generated);
  }
}
