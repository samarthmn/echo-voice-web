import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(project, 'design-system', 'styles.css');

/** The self-hosted faces in public/fonts (see public/fonts/README.md). */
const FONT_FACES = [
  [
    'Mulish',
    'mulish-latin-ext-wght-normal.woff2',
    '200 1000',
    'normal',
    'woff2-variations',
    'latin-ext',
  ],
  ['Mulish', 'mulish-latin-wght-normal.woff2', '200 1000', 'normal', 'woff2-variations', 'latin'],
  [
    'Mulish',
    'mulish-latin-ext-wght-italic.woff2',
    '200 1000',
    'italic',
    'woff2-variations',
    'latin-ext',
  ],
  ['Mulish', 'mulish-latin-wght-italic.woff2', '200 1000', 'italic', 'woff2-variations', 'latin'],
] as const;
export const FONT_FILES = FONT_FACES.map(([, file]) => file);

const UNICODE_RANGE = {
  latin:
    'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  'latin-ext':
    'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
} as const;

const LIGHT_SELECTOR = ':root';
const DARK_SELECTOR = "[data-theme='dark']";

/** Top-level `selector { body }` rules of a stylesheet, comments removed. */
function topLevelRules(css: string): { selector: string; body: string }[] {
  const source = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const rules: { selector: string; body: string }[] = [];
  let start = 0;
  let depth = 0;
  let open = -1;
  for (let i = 0; i < source.length; i++) {
    const char = source[i];
    if (char === '{') {
      if (depth === 0) open = i;
      depth++;
    } else if (char === '}') {
      depth--;
      if (depth < 0) throw new Error('Unbalanced braces in design-system/styles.css.');
      if (depth === 0) {
        rules.push({
          selector: source
            .slice(start, open)
            .replace(/@import[^;]*;/g, '')
            .trim(),
          body: source.slice(open + 1, i),
        });
        start = i + 1;
      }
    } else if (char === ';' && depth === 0) {
      start = i + 1;
    }
  }
  return rules;
}

/** Custom-property declarations of a rule body, in source order. */
function declarations(body: string): Map<string, string> {
  const result = new Map<string, string>();
  for (const part of body.split(';')) {
    const match = /^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/.exec(part);
    if (match?.[1] && match[2]) result.set(match[1], match[2].replace(/\s+/g, ' '));
  }
  return result;
}

function block(rules: { selector: string; body: string }[], selector: string): string {
  const found = rules.filter((rule) => rule.selector === selector);
  if (found.length !== 1)
    throw new Error(`Expected one "${selector}" block in design-system/styles.css.`);
  return found[0]?.body ?? '';
}

/** The light and dark token sets declared in the design-system source. */
export function tokenSets(css: string): { light: Map<string, string>; dark: Map<string, string> } {
  const rules = topLevelRules(css);
  return {
    light: declarations(block(rules, LIGHT_SELECTOR)),
    dark: declarations(block(rules, DARK_SELECTOR)),
  };
}

/** Light-block properties that are not custom properties (e.g. color-scheme). */
function plainProperties(body: string): string[] {
  return body
    .split(';')
    .map((part) => part.trim().replace(/\s+/g, ' '))
    .filter((part) => part && !part.startsWith('--'));
}

function render(set: Map<string, string>, extra: string[], indent: string): string {
  return [...[...set].map(([name, value]) => `${name}: ${value}`), ...extra]
    .map((line) => `${indent}${line};`)
    .join('\n');
}

/** tokens.css: font faces plus the light, dark and system-dark token blocks. */
function tokensCss(css: string, fontBase: string): string {
  const rules = topLevelRules(css);
  const lightBody = block(rules, LIGHT_SELECTOR);
  const darkBody = block(rules, DARK_SELECTOR);
  const light = declarations(lightBody);
  const dark = declarations(darkBody);
  const faces = FONT_FACES.map(
    ([family, file, weight, style, format, subset]) =>
      `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('${fontBase}${file}') format('${format}');\n  unicode-range: ${UNICODE_RANGE[subset]};\n}`,
  );
  return [
    '/* Generated by scripts/build-tokens.ts from design-system/styles.css. Do not edit. */',
    ...faces,
    `:root {\n${render(light, plainProperties(lightBody), '  ')}\n}`,
    `:root[data-theme='dark'] {\n${render(dark, plainProperties(darkBody), '  ')}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${render(dark, plainProperties(darkBody), '    ')}\n  }\n}`,
    '',
  ].join('\n\n');
}

export async function readTokenSource(): Promise<string> {
  return readFile(SOURCE, 'utf8');
}

/** Write tokens.css to `file`, with font URLs relative to `fontBase`. */
export async function writeTokens(file: string, fontBase: string): Promise<void> {
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, tokensCss(await readTokenSource(), fontBase));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await writeTokens(path.join(project, 'public', 'tokens.css'), '/fonts/');
}
